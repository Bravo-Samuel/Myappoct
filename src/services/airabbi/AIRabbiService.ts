import { ChatSessionManager, ChatSessionState } from './ChatSessionManager';
import { ConversationService, ConversationThread } from './ConversationService';
import { PromptTemplateService } from './PromptTemplateService';
import { knowledgeSourceService, KnowledgeSource } from './KnowledgeSourceService';
import { CalendarService } from '../data/CalendarService';
import { HebrewCalendarService } from '../data/HebrewCalendarService';
import { SupportedLanguage } from '../../types';

export class AIRabbiService {
  private static sessionManagers: Map<string, ChatSessionManager> = new Map();

  /**
   * Get or create a session manager for a specific user ID
   */
  public static getSessionManager(userId: string = 'guest-user'): ChatSessionManager {
    let mgr = this.sessionManagers.get(userId);
    if (!mgr) {
      mgr = new ChatSessionManager(userId);
      mgr.initialize();
      this.sessionManagers.set(userId, mgr);
    }
    return mgr;
  }

  /**
   * Helper to format clipboard copy text cleanly with citation
   */
  public static formatResponseForCopy(text: string): string {
    return `${text}\n\n—\nGenerated by AI Rabbi & Torah Advisor • Bnei Menashe Digital Platform`;
  }

  /**
   * Helper to share response (Web Share API or copy link)
   */
  public static async shareResponse(title: string, text: string): Promise<boolean> {
    if (navigator.share) {
      try {
        await navigator.share({
          title: `AI Rabbi Responsum: ${title}`,
          text: `${text.substring(0, 300)}...\n\nRead more on Bnei Menashe Digital Platform`,
          url: window.location.href
        });
        return true;
      } catch (e) {
        // User cancelled or share failed
        return false;
      }
    }
    return false;
  }

  /**
   * Get Current Platform Calendar Summary for UI injection display
   */
  public static getLivePlatformContext(location: string = 'Churachandpur') {
    const isIsrael = location.toLowerCase().includes('israel');
    const hebrewDate = HebrewCalendarService.getHebrewDateInfo(new Date(), isIsrael);
    const parashah = HebrewCalendarService.getParashatHaShavua(new Date(), isIsrael);

    return {
      gregorianDate: hebrewDate.gregorianFormatted,
      hebrewDateEn: hebrewDate.hebrewDateFormattedEn,
      hebrewDateHe: hebrewDate.hebrewDateFormattedHe,
      parashahEn: parashah.nameEn,
      parashahHe: parashah.nameHe,
      omer: hebrewDate.omer ? `Day ${hebrewDate.omer.dayNumber}` : null,
      holidays: hebrewDate.holidays.map(h => h.nameEn)
    };
  }
}

export {
  ChatSessionManager,
  ConversationService,
  PromptTemplateService,
  knowledgeSourceService
};
export type { ChatSessionState, ConversationThread, KnowledgeSource };
